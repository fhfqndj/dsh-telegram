/** Язык по коду из Telegram: всё, что не английский, считаем русским. */
export function languageFromTelegram(code) {
  return typeof code === 'string' && code.toLowerCase().startsWith('en') ? 'en' : 'ru'
}

/** Допустимый язык или undefined. */
export function normalizeLanguage(value) {
  return LANGS.includes(value) ? value : undefined
}
